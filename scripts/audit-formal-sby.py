#!/usr/bin/env python3
"""Independently derive every SBY comparison CSV column from complete evidence."""

import argparse
import csv
import hashlib
import importlib.util
import io
import json
import math
from pathlib import Path, PurePosixPath
import re
import shlex


SPEC = importlib.util.spec_from_file_location("sby_artifacts", Path(__file__).with_name("sby-artifact-audit.py"))
ARTIFACTS = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(ARTIFACTS)
require, strict_json = ARTIFACTS.require, ARTIFACTS.strict_json
COLUMNS = "solver case mode depth expected status kind exitCode elapsedMs artifactCount comparedCount sqliteSha256 modelSha256 solverSha256 yosysSha256 error".split()
CASES = {
    "bmc-prefix": ("bmc", 2, "PASS", "bounded-pass", 0),
    "bmc-violation": ("bmc", 6, "FAIL", "counterexample", 2),
    "prove-inconclusive": ("prove", 2, "UNKNOWN", "unknown", 4),
    "prove-invariant": ("prove", 6, "PASS", "proved", 0),
    "cover-reached": ("cover", 6, "PASS", "covered", 0),
    "cover-unreached": ("cover", 6, "FAIL", "unreached", 2),
}
SNAPSHOTS = {"scripts/probe-formal-sby.mjs", "scripts/probe-upstream-formal.mjs", "scripts/audit-formal-sby.py", "scripts/sby-artifact-audit.py",
             "web/formal_process.py", "patches/sby-process.patch", "patches/yosys-smtio-process.patch", "tests/synth/formal-sby-cases.mjs", "package-lock.json"}


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def positive(value):
    return type(value) in [int, float] and math.isfinite(value) and value > 0


def cell(value):
    return "" if value is None else str(value)


class Evidence:
    def __init__(self, directory):
        self.directory = Path(directory).resolve(strict=True)

    def path(self, name):
        path = PurePosixPath(name)
        require(name and str(path) == name and not path.is_absolute() and ".." not in path.parts, "unsafe evidence path")
        current = self.directory
        for part in path.parts:
            current /= part
            require(not current.is_symlink(), "symlink evidence")
        return current

    def read(self, name):
        return self.path(name).read_bytes()

    def data(self, name):
        return strict_json(self.read(name))

    def files(self, name):
        directory = self.path(name)
        result = set()
        for item in directory.rglob("*"):
            relative = item.relative_to(self.directory).as_posix()
            self.path(relative)
            require(item.is_file() or item.is_dir(), "special evidence file")
            if item.is_file():
                result.add(item.relative_to(directory).as_posix())
        return result


def artifact_names(case):
    mode, _, status, _, _ = CASES[case]
    names = {"job.sby", "top.v", "result/config.sby", "result/job.xml", "result/logfile.txt", "result/src/top.v", "result/status", "result/status.sqlite", "result/" + status}
    names.update("result/model/" + name for name in ["design.il", "design.json", "design.log", "design.ys", "design_prep.il", "design_prep.log", "design_prep.ys", "design_smt2.log", "design_smt2.smt2", "design_smt2.ys"])
    logs = ["logfile_basecase.txt", "logfile_induction.txt"] if mode == "prove" else ["logfile.txt"]
    names.update("result/engine_0/" + name for name in logs)
    trace = {"bmc-violation": "trace", "prove-inconclusive": "trace_induct", "cover-reached": "trace0"}.get(case)
    if trace:
        names.update("result/engine_0/" + trace + suffix for suffix in [".vcd", ".yw", "_tb.v", ".smtc"])
    return names


def canonical(auditor, evidence, prefix, name, runtime):
    raw = evidence.read(prefix + "/" + name)
    require(raw, "empty artifact: " + name)
    if name == "result/status.sqlite":
        return auditor.database(evidence.path(prefix + "/" + name), runtime)
    if name == "result/model/design.json":
        return auditor.jny(raw, runtime)
    if name == "result/job.xml":
        return auditor.junit(raw, runtime)
    text = raw.decode("utf-8", errors="strict")
    if name == "result/logfile.txt" or name in ["result/PASS", "result/FAIL", "result/UNKNOWN"]:
        return auditor.root_log(text, runtime)
    if name == "result/status":
        match = re.fullmatch(r"(PASS|FAIL|UNKNOWN) ([0-9]+) ([0-9]+)\n", text)
        require(match is not None, "SBY status format")
        auditor.variation("status elapsed seconds", runtime, int(match[3]))
        return match.group(1, 2)
    if name.startswith("result/model/") and name.endswith(".log"):
        return auditor.yosys_log(text, runtime)
    if name.endswith((".il", ".smt2")):
        prefix = "# Generated by " if name.endswith(".il") else "; SMT-LIBv2 description generated by "
        first, rest = text.split("\n", 1)
        require(first.startswith(prefix), "missing Yosys artifact provenance")
        return prefix + auditor.generator(first[len(prefix):], runtime) + "\n" + rest
    if name.startswith("result/engine_0/logfile"):
        return re.sub(r"^## +[0-9]+:[0-9]{2}:[0-9]{2} +", "## TIME ", text, flags=re.M)
    return raw


def audit_case(evidence, meta, native_meta, row, csv_row):
    solver, case = row["solver"], row["case"]
    require(solver in ["yices2", "z3"] and case in CASES, "unknown SBY condition")
    mode, depth, status, kind, code = CASES[case]
    label = solver + "-" + case
    data = lambda name: evidence.data(label + "/" + name)
    read = lambda name: evidence.read(label + "/" + name)
    require(row == data("result.json"), "per-condition result")
    native, transport = data("native.json"), data("transport.json")
    require(native["error"] is None and native["signal"] is None and type(native["exitCode"]) is int and native["exitCode"] == code, "native termination")
    require(native["solverSha256"] == meta["probes"][solver]["nativeSha256"], "native solver binary")
    require(transport["status"] == "exited" and transport["integrityVerified"] is True and type(transport["exitCode"]) is int and transport["exitCode"] == code, "SBY termination")
    require(positive(native["elapsedMs"]) and positive(transport["elapsedMs"]), "SBY elapsed time")
    for key, expected in {"solver": solver, "case": case, "mode": mode, "depth": depth, "expected": status, "status": status, "kind": kind}.items():
        require(native[key] == expected, "native result: " + key)
    names = artifact_names(case)
    require(evidence.files(label + "/pyodide") == names, "returned artifact set")
    require(set(native["files"]) == evidence.files(label + "/native") == names | {"stdout.log", "stderr.log"}, "native artifact set")
    for name, info in native["files"].items():
        raw = read("native/" + name)
        require(info == {"bytes": len(raw), "sha256": digest(raw)}, "native inventory: " + name)
    auditor = ARTIFACTS.ArtifactAudit(meta["sources"]["pins"]["yosys"], native_meta["nativeCommands"])
    for runtime in ["native", "pyodide"]:
        stdout = read("native/stdout.log" if runtime == "native" else "stdout.log")
        require(read("native/stderr.log" if runtime == "native" else "stderr.log") == b"", "SBY stderr")
        require(stdout == read(runtime + "/result/logfile.txt"), "root stdout/logfile mismatch")
        require(re.search(rb" DONE \(" + status.encode() + b", rc=" + str(code).encode() + rb"\)\n$", stdout), "final SBY line")
        require(read(runtime + "/result/status").startswith(f"{status} {code} ".encode()), "status disagrees with termination")
        xml = ARTIFACTS.ET.fromstring(read(runtime + "/result/job.xml"))
        require(xml.find("testsuite/properties/property[@name='status']").get("value") == status, "JUnit status")
        require(xml[0].get("time") == read(runtime + "/result/status").decode().split()[2], "JUnit elapsed seconds")
        wall = re.findall(rb"summary: Elapsed clock time \[H:MM:SS \(secs\)\]: [0-9]+:[0-9]{2}:[0-9]{2} \(([0-9]+)\)", stdout)
        require(wall == [read(runtime + "/result/status").split()[2]], "status/log elapsed seconds")
    canonical_hash = hashlib.sha256()
    for name in sorted(names):
        value = canonical(auditor, evidence, label + "/native", name, "native")
        require(value == canonical(auditor, evidence, label + "/pyodide", name, "pyodide"), "artifact differs: " + name)
        encoded = [name, type(value).__name__, value.hex() if isinstance(value, bytes) else value]
        canonical_hash.update(json.dumps(encoded, sort_keys=True, ensure_ascii=True, allow_nan=False, separators=(",", ":")).encode() + b"\n")
    database = auditor.database(evidence.path(label + "/pyodide/result/status.sqlite"), "pyodide")
    def table(name):
        info = database["tables"][name]
        columns = [column[1] for column in info["columns"] if column[1] != "created"]
        return [dict(zip(columns, values, strict=True)) for values in info["rows"]]
    tasks = table("task")
    require(len(tasks) == 1 and tasks[0]["mode"] == mode and tasks[0]["workdir"] == "result", "SQLite task identity")
    status_rows = table("task_status")
    require([item["status"] for item in status_rows] == ([] if status == "UNKNOWN" else [status]), "SQLite final status")
    traces = table("task_trace")
    require({"result/" + item["path"] for item in traces} == {name for name in names if name.endswith((".vcd", ".yw"))}, "SQLite trace inventory")
    require(all(item["engine_case"] == ("induction" if case == "prove-inconclusive" else None) for item in traces), "SQLite trace phase")
    require(auditor.root_log(read("native/stdout.log").decode(), "native") == auditor.root_log(read("stdout.log").decode(), "pyodide"), "SBY stdout comparison")
    require(read("native/top.v") == read("native/result/src/top.v"), "copied HDL source")
    require(read("native/job.sby") == read("native/result/config.sby"), "copied SBY config")
    config = read("native/job.sby").decode()
    require(f"mode {mode}\ndepth {depth}\n" in config and f"smtbmc {'yices' if solver == 'yices2' else 'z3'}\n" in config, "SBY fixture configuration")
    children = transport["children"]
    require(len(children) == (5 if mode == "prove" else 4), "SBY tool child count")
    canonical_log = auditor.root_log(read("stdout.log").decode(), "pyodide")
    commands = [shlex.split(command) for command in re.findall(r': starting process "cd result(?:/(?:src|model))?; ([^\n]+)"\n', canonical_log)]
    require([child["args"] for child in children] == commands, "launched tool argv")
    identities = set()
    for index, child in enumerate(children):
        require(child["processId"].startswith(transport["jobId"] + ":tool:") and child["processId"] not in identities, "tool process identity")
        identities.add(child["processId"])
        require(child["status"] == "exited" and child["role"] == "tool" and child["expectedTermination"] is False and child["integrityVerified"] is True, "tool termination")
        expected_code = int(index >= 3 and (case in ["bmc-violation", "cover-unreached"] or (case == "prove-inconclusive" and index == 4)))
        require(type(child["exitCode"]) is int and child["exitCode"] == expected_code, "tool ordinary exit code")
        if index < 3:
            require(child["args"][0] == "yosys", "synthesis tool")
            continue
        require(child["args"][0] == "yosys-smtbmc" and ("-i" in child["args"]) == (mode == "prove" and index == 4), "SMTBMC phase")
        log_name = "logfile_induction.txt" if index == 4 else "logfile_basecase.txt" if mode == "prove" else "logfile.txt"
        require(re.search(rb"Status: " + (b"failed" if expected_code else b"passed") + rb"\n$", read("pyodide/result/engine_0/" + log_name)), "SMTBMC phase status")
        require(len(child["children"]) == 1, "solver child count")
        actual = child["children"][0]
        require(actual["status"] == "exited" and actual["integrityVerified"] is True and type(actual["exitCode"]) is int and actual["exitCode"] == 0 and actual["error"] is None, "solver termination")
        require(actual["sha256"] == meta["probes"][solver]["sha256"] and positive(actual["elapsedMs"]) and positive(actual["memoryBytes"]), "solver identity or resource")
        require(actual["args"] == (["yices-smt2", "--incremental"] if solver == "yices2" else ["z3", "-smt2", "-in"]), "solver argv")
        require(type(actual["stdoutBytes"]) is int and actual["stdoutBytes"] > 0 and type(actual["stderrBytes"]) is int and actual["stderrBytes"] == 0, "solver output")
    compared = sum(bool(re.search(r"\.(?:v|sby|ys|il|smt2|vcd|yw|smtc)$", name) or re.fullmatch(r"result/engine_0/logfile.*\.txt", name)) for name in names)
    derived = dict(zip(["mode", "depth", "expected", "kind", "exitCode"], [mode, depth, status, kind, code]))
    derived.update({"solver": solver, "case": case, "status": status, "elapsedMs": transport["elapsedMs"], "artifactCount": len(names), "comparedCount": compared,
                    "sqliteSha256": digest(read("pyodide/result/status.sqlite")), "modelSha256": digest(read("pyodide/result/model/design_smt2.smt2")),
                    "solverSha256": meta["probes"][solver]["sha256"], "yosysSha256": meta["yosys"]["sha256"], "error": None})
    require(set(row) == set(COLUMNS) and all(type(row[key]) is type(derived[key]) and row[key] == derived[key] for key in COLUMNS), "JSON raw evidence")
    require(csv_row == {key: cell(derived[key]) for key in COLUMNS}, "CSV raw evidence")
    return {"condition": label, "artifacts": len(names), "columns": len(COLUMNS), "canonicalSha256": canonical_hash.hexdigest(), "variations": auditor.variations}


def audit(directory):
    evidence = Evidence(directory)
    meta, start = evidence.data("metadata-final.json"), evidence.data("metadata.json")
    require(meta["format"] == 1 and type(meta["preliminary"]) is bool and meta["worktree"] == "" and re.fullmatch(r"[a-f0-9]{40}", meta["commit"]), "clean comparison provenance")
    require({key: value for key, value in meta.items() if key != "probes"} == {key: value for key, value in start.items() if key != "probes"}, "changed comparison metadata")
    native_meta = evidence.data("native-metadata.json")
    require(digest(evidence.read("native-metadata.json")) == meta["nativeMetadataSha256"], "native metadata hash")
    require(native_meta["worktree"] == "" and native_meta["commit"] == meta["commit"] and native_meta["runtime"] == "native", "clean matching native harness")
    require(native_meta["preliminary"] is meta["preliminary"], "matching native measurement mode")
    require(set(native_meta["nativeCommands"]) == {"yosys", "yosys-smtbmc", "yosys-witness"}, "native executable metadata")
    require(native_meta["python"] and native_meta["yosys"]["version"] and meta["node"] and meta["pyodidePackage"], "runtime versions")
    for name, sha in {"yosys.wasm": meta["yosys"]["sha256"], "yosys-share.tar": meta["yosys"]["shareSha256"], "yosys-native": native_meta["yosys"]["sha256"]}.items():
        require(digest(evidence.read("inputs/" + name)) == sha, "Yosys binary or share: " + name)
    require(SNAPSHOTS <= set(meta["snapshots"]), "missing harness snapshot")
    require(meta["preliminary"] or "scripts/measure-formal-sby.py" in meta["snapshots"], "missing measurement runner snapshot")
    for name, sha in meta["snapshots"].items():
        require(digest(evidence.read("snapshots/" + name)) == sha, "snapshot hash: " + name)
    for name, sha in native_meta["sources"].items():
        if name in meta["snapshots"]:
            require(sha == meta["snapshots"][name], "native source hash: " + name)
    require(evidence.data("assets/manifest.json") == meta["sources"], "Python source manifest")
    pins = dict((name, sha) for sha, name in re.findall(r"^160000 commit ([a-f0-9]{40})\tvendor/(click|yosys|sby)$", native_meta["pins"], flags=re.M))
    require(pins == meta["sources"]["pins"] and len(pins) == 3, "matching pinned Python sources")
    for origin in meta["sources"]["origins"].values():
        if origin["source"].endswith(".py"):
            name = "vendor/" + origin["submodule"] + "/" + origin["source"]
            require(native_meta["sources"][name] == origin["original_sha256"], "original Python source: " + name)
    for name, sha in meta["sources"]["patches"].items():
        require(meta["snapshots"]["patches/" + name] == sha, "staged transport patch")
    assets = meta["sources"]["assets"]
    require(assets and len({item["path"] for item in assets}) == len(assets), "duplicate or missing Python source asset")
    require(evidence.files("assets") == {item["path"] for item in assets} | {"manifest.json"}, "complete Python source set")
    for item in assets:
        raw = evidence.read("assets/" + item["path"])
        require(len(raw) == item["size"] and digest(raw) == item["sha256"], "Python source hash")
    require(set(meta["probes"]) == {"yices2", "z3"}, "solver set")
    for solver, probe in meta["probes"].items():
        raw = evidence.read("build/" + solver + ".json")
        require(digest(raw) == probe["metadataSha256"], "solver build metadata hash")
        build = strict_json(raw)
        require(build["status"] == "built" and build["worktree_status"] == "" and build["artifact"]["sha256"] == probe["sha256"], "successful clean solver build")
        native_raw = evidence.read("build/" + solver + "-native.json")
        require(digest(native_raw) == probe["nativeMetadataSha256"], "native solver build metadata hash")
        native_build = strict_json(native_raw)
        require(native_build["status"] == "built" and native_build["worktree_status"] == "" and native_build["artifact"]["sha256"] == probe["nativeSha256"], "successful native solver build")
        require(native_build["source"] == build["source"], "same pinned solver source")
        for name, sha in {solver + ".wasm": probe["sha256"], solver + "-native": probe["nativeSha256"]}.items():
            require(digest(evidence.read("inputs/" + name)) == sha, "executed solver binary")
    reader = csv.DictReader(io.StringIO(evidence.read("results.csv").decode()), strict=True)
    require(reader.fieldnames == COLUMNS, "CSV columns")
    csv_rows = list(reader)
    results = evidence.data("results.json")
    require(results["preliminary"] is meta["preliminary"] and len(results["rows"]) == len(csv_rows) == 12, "complete condition matrix")
    identities = [(row["solver"], row["case"]) for row in results["rows"]]
    require(set(identities) == {(solver, case) for solver in ["yices2", "z3"] for case in CASES} and len(set(identities)) == len(identities), "unique complete conditions")
    reports = [audit_case(evidence, meta, native_meta, row, csv_row) for row, csv_row in zip(results["rows"], csv_rows, strict=True)]
    return {"status": "pass", "preliminary": meta["preliminary"], "commit": meta["commit"], "rows": len(reports), "columns": len(COLUMNS), "artifacts": sum(report["artifacts"] for report in reports), "conditions": reports}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    report = audit(args.directory)
    if args.out:
        with args.out.open("x") as stream:
            json.dump(report, stream, ensure_ascii=True, indent=2)
            stream.write("\n")
    print(json.dumps({key: value for key, value in report.items() if key != "conditions"}, sort_keys=True))
